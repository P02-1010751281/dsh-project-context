/**
 * Mechanical session index: `<memory>/session-logs/INDEX.md`.
 *
 * One line per archived session, written without any model call — the archive
 * step (S0) owns it. The title comes from dsh's own `session/title` event,
 * falling back to the first user message. Later passes (autolearn backtracking,
 * handoff pointers) read the index to navigate the raw archive.
 */

import { readdir, rm, stat } from "node:fs/promises";
import path from "node:path";
import type { Session } from "@deepseek-ai/dsh-session";
import { legacySessionIndexFile, logsDir, memoryDir, readOptional, safeSessionId, sessionIndexFile, writeAtomic } from "../shared/project-state.js";
import { withMemoryLock } from "../shared/lock.js";
import { clipTitle } from "../shared/text.js";
import { isHandoffContinuationText } from "../project-handoff/language.js";
import { piTextOf } from "./archive.js";
import { isDirectory, readSessionMeta, writeSessionMeta } from "./session-meta.js";
import type { SessionMeta } from "./session-meta.js";
import type { PiBlock } from "./archive.js";

export interface SessionIndexEntry {
	id: string;
	date: string;
	title: string;
	/** Absolute path of the session's Markdown rendering. */
	file: string;
	/** Absolute path of the canonical JSONL archive (the source for backtracking). */
	raw: string;
}

type SessionEntry = ReturnType<Session["snapshotEvents"]>[number];

const HEADING = "# Session Index";
const MAX_TITLE_CHARS = 160;
/** `- [id](<id>/session.jsonl) — YYYY-MM-DD — title` (the link target is ignored on parse). */
const LINE_PATTERN = /^- \[([^\]]+)\]\(([^)]+)\) — (\d{4}-\d{2}-\d{2}) — (.*)$/;

function textOf(content: readonly { type: string; text?: string }[]): string {
	return content
		.filter((block) => block.type === "text" && typeof block.text === "string")
		.map((block) => block.text)
		.join(" ")
		.trim();
}

/**
 * pi's own continuation prompt, matched the way pi matches it: `isHandoffPromptText` in the
 * sibling's `handoff/language.ts` (read at pi `8b300dc`) requires the preamble prefix, a section
 * heading only a generated prompt carries, *and* the closing line. Replicated rather than
 * imported because pi is a separate repository and not a runtime dependency of this plugin; the
 * three-part conjunction is what keeps a user message that merely mentions a handoff usable as a
 * title. It belongs here because this repo archives pi-format logs: `01a09821` (2026-09-13) was
 * titled by an 11,384-character pi seed instead of the user's own first message.
 */
const PI_PROMPT_PREFIXES = [
	"This session continues work handed off from a previous session (",
	"本会话接手上一会话（",
] as const;

/** Section headings that only a generated pi continuation prompt contains. */
const PI_PROMPT_HEADINGS = ["## Handoff Summary", "## Previous session details", "## 交接摘要", "## 上一会话信息"] as const;

/** Closing lines every generated pi continuation prompt ends with. */
const PI_PROMPT_CLOSINGS = [
	"Continue the task from where it left off.",
	"The task is paused on the pending question above. Do not choose an option or start work on the user's behalf; wait for their answer.",
	"从上次中断处继续。",
	"任务停在上面的问题上。不要替用户选选项或开工，等用户回答。",
] as const;

function isPiHandoffPrompt(text: string): boolean {
	const trimmed = text.trim();
	if (trimmed.length === 0) return false;
	if (!PI_PROMPT_PREFIXES.some((prefix) => trimmed.startsWith(prefix))) return false;
	if (!PI_PROMPT_HEADINGS.some((heading) => trimmed.includes(heading))) return false;
	return PI_PROMPT_CLOSINGS.some((closing) => trimmed.endsWith(closing));
}

/**
 * Whether a user-role message was generated by a handoff rather than written by a person —
 * this plugin's own continuation prompt, or the pi sibling's in a pi archive dsh imported.
 *
 * Both are `user`-role messages with no marker of their own (dsh's prompt RPC carries no source
 * kind), so they must not become a session title. Accepted residual, same as the detectors it
 * composes: a message that reproduces a generated prompt verbatim is indistinguishable from one.
 */
function isGeneratedPrompt(text: string): boolean {
	return isHandoffContinuationText(text) || isPiHandoffPrompt(text);
}

/**
 * Title from a bare event list: `session/title`, else the first user message a handoff did not
 * generate, else a fallback. Both harnesses that write into `.agents/` are read — dsh's named
 * events and pi's bare `message` event — so a pi archive imported by dsh gets the same title the
 * live path would.
 */
export function sessionTitleFromEntries(events: readonly unknown[]): string {
	let title = "";
	let firstUser = "";
	for (const raw of events) {
		const event = raw as SessionEntry;
		// `session/title` is emitted by dsh at runtime; its type is not part of the
		// base SessionEventMap, so read it structurally instead of narrowing.
		const type = event.type as string;
		if (type === "session/title") {
			const data = event.data as { title?: unknown };
			if (typeof data.title === "string" && data.title.trim()) title = data.title;
			continue;
		}
		if (!firstUser && event.type === "user/message" && event.data.source.kind === "user") {
			// A handoff seed is a `user/message` like any other — the prompt RPC carries no source
			// kind — so without this the plugin's own banner titles the successor session. An empty
			// body leaves `firstUser` falsy, so a later message can still title the session.
			const text = textOf(event.data.content);
			if (!isGeneratedPrompt(text)) firstUser = text;
			continue;
		}
		// pi writes `{"type":"message","message":{role,content:[…]}}` where dsh writes one named
		// event per message under `data`; the event name `message` is disjoint from every dsh event
		// name, so this branch cannot change what a dsh log resolves to. A pi archive imported by
		// dsh would otherwise index as "Untitled session" — the one label autolearn navigates by.
		// The body is read as unknown (not `SessionEntry`) because a pi line is not a dsh event.
		// `piTextOf` (archive.ts) is reused rather than this file's `textOf`: the two join the text
		// blocks differently, so a multi-block message would title as `"a b"` while the archive
		// reader renders `"ab"` — the same message, two different strings. One extraction, one text.
		if (!firstUser && type === "message") {
			const message = (raw as { message?: unknown }).message;
			const pi = typeof message === "object" && message !== null ? (message as { role?: unknown; content?: unknown }) : undefined;
			if (pi?.role === "user" && Array.isArray(pi.content)) {
				const text = piTextOf(pi.content as PiBlock[]);
				if (!isGeneratedPrompt(text)) firstUser = text;
			}
		}
	}
	return clipTitle(title || firstUser || "Untitled session", MAX_TITLE_CHARS);
}

/** Title dsh itself assigned to the session, else the first user message, else a fallback. */
export function sessionTitle(session: Session): string {
	return sessionTitleFromEntries(session.snapshotEvents());
}

/**
 * One Markdown index line from its parts. Links are relative to `session-logs/`.
 *
 * The link points at `session.jsonl`, the canonical log, rather than the rendered
 * `session.md`: the JSONL is what every reader actually opens (autolearn's backtrack,
 * the import completeness check) and it is never pruned, while the rendering is
 * reproducible from it and may be deleted to reclaim disk. Deleting it is only safe
 * once that is acceptable to every pointer: `performHandoff` writes the successor's
 * handoff document against `session.md`, so a deleted rendering leaves that pointer
 * dangling until the session renders again. Parsing ignores the target, so both
 * forms read identically.
 */
export function sessionIndexLineFrom(id: string, createdAt: number, title: string): string {
	return sessionIndexLineFor({ id, date: new Date(createdAt).toISOString().slice(0, 10), title });
}

/** One Markdown index line. Links are relative to `session-logs/`. */
export function sessionIndexLine(session: Session, title: string = sessionTitle(session)): string {
	return sessionIndexLineFrom(String(session.id), session.header.createdAt, title);
}

/**
 * Convert pre-move index links (`session-logs/<id>/session.md`) to the current relative form.
 * @param document - the legacy index body.
 * @returns the body with every link made relative to `session-logs/`.
 */
export function normalizeLegacyIndex(document: string): string {
	return document
		.split("\n")
		.map((line) => line.replace(/\]\(session-logs\//, "]("))
		.join("\n");
}

/** Parse an INDEX.md body; unrecognized lines are ignored. */
export function parseSessionIndex(text: string): Array<{ id: string; date: string; title: string }> {
	const entries: Array<{ id: string; date: string; title: string }> = [];
	for (const raw of text.split("\n")) {
		const match = LINE_PATTERN.exec(raw.trim());
		if (match) entries.push({ id: match[1]!, date: match[3]!, title: match[4]!.trim() });
	}
	return entries;
}

function indexLineId(line: string): string {
	return /^- \[([^\]]+)\]/.exec(line)?.[1] ?? line;
}


/** The `- [id](…)` lines of an index body; a heading, prose or a blank line is not an entry. */
function entryLines(document: string): string[] {
	return document.split("\n").map((current) => current.trim()).filter((current) => current.startsWith("- ["));
}


/**
 * The pre-move index at `<memory>/session-index.md`, ready for adoption, or `undefined` when there
 * is nothing to adopt: no regular file there (`stat` also keeps a directory or a FIFO from making
 * every later write fail or block), or a file holding no index line at all — a hand-written note is
 * not an index and must not be deleted.
 */
async function readLegacyIndexForAdoption(file: string): Promise<{ body: string; ids: string[]; size: number; mtimeMs: number } | undefined> {
	try {
		const info = await stat(file);
		if (!info.isFile()) return undefined;
		const body = normalizeLegacyIndex(await readOptional(file));
		const ids = entryLines(body).map((current) => indexLineId(current));
		return ids.length === 0 ? undefined : { body, ids, size: info.size, mtimeMs: info.mtimeMs };
	} catch {
		return undefined;
	}
}

/**
 * Whether an adopted file still has the size and mtime it had when it was read. Exported for its
 * own unit test: the check has to notice an *append* (same inode, new size/mtime), and the
 * end-to-end adoption test cannot reach that case — there the write replaces the path and so
 * changes the inode too, which an identity-based (and append-blind) check would also catch.
 */
export async function untouchedSince(file: string, adopted: { size: number; mtimeMs: number }): Promise<boolean> {
	try {
		const info = await stat(file);
		return info.size === adopted.size && info.mtimeMs === adopted.mtimeMs;
	} catch {
		return false;
	}
}

/** Read the index with absolute paths so later passes can open the archives directly. */
export async function readSessionIndex(projectRoot: string): Promise<SessionIndexEntry[]> {
	const text = await readOptional(sessionIndexFile(projectRoot));
	return parseSessionIndex(text).map((entry) => ({
		...entry,
		file: path.join(logsDir(projectRoot), safeSessionId(entry.id), "session.md"),
		raw: path.join(logsDir(projectRoot), safeSessionId(entry.id), "session.jsonl"),
	}));
}

/**
 * Every archived session's metadata, in directory-name order.
 *
 * The read-only half of the walk `regenerateSessionIndex` performs below; that one also writes metadata
 * back for a directory that predates `meta.json`, so it cannot serve a reader. A directory whose
 * metadata is unreadable is skipped rather than failing the listing: the next index write rebuilds it
 * from the archive, and a navigation command must not be the thing that breaks on one bad file.
 * @param projectRoot - the project whose archive to list.
 * @returns every session's metadata; empty when the archive directory does not exist yet.
 */
export async function listArchivedSessions(projectRoot: string): Promise<SessionMeta[]> {
	const logs = logsDir(projectRoot);
	let names: string[];
	try {
		names = await readdir(logs);
	} catch {
		return [];
	}
	const metas: SessionMeta[] = [];
	for (const name of names.sort()) {
		if (!SESSION_DIRECTORY.test(name)) continue;
		const dir = path.join(logs, name);
		if (!(await isDirectory(dir))) continue;
		const meta = await readSessionMeta(dir);
		if (meta !== undefined) metas.push(meta);
	}
	return metas;
}

/**
 * Cross-process lock target for one project's index, so the lock file is
 * `<memory>/session-index.lock`. It lives in the memory directory because that
 * directory's `.gitignore` already covers `*.lock`, while `session-logs/` owns a
 * different ignore file (a bare `*`) that the lock helper must not append to.
 */
function sessionIndexLockTarget(projectRoot: string): string {
	return path.join(memoryDir(projectRoot), "session-index");
}

/** One rendered index line from a session's metadata: `<id> — <date> — <title>`. */
export function sessionIndexLineFor(meta: SessionMeta): string {
	const safe = safeSessionId(meta.id);
	return `- [${safe}](${safe}/session.jsonl) — ${meta.date} — ${clipTitle(meta.title, MAX_TITLE_CHARS)}`;
}

/** The metadata a live session contributes: its own id, creation date and title. */
function sessionMetaOf(session: Session): SessionMeta {
	return {
		id: safeSessionId(String(session.id)),
		date: new Date(session.header.createdAt).toISOString().slice(0, 10),
		title: sessionTitle(session),
		...(session.header.origin === "subagent" ? { kind: "subagent" as const } : {}),
	};
}

interface ArchiveHeaderHint {
	date: string;
	origin?: "subagent";
}

/**
 * The parts of a `session.jsonl` header the index needs, for a directory that has no `meta.json`.
 *
 * This is the migration read: it runs once per session on the first generation after an upgrade and
 * writes the metadata, so the next write does not open the archive again. The header is the first
 * line (dsh writes `createdAt` as a number, pi a `timestamp` string), so a file that does not parse
 * as JSON simply contributes nothing instead of failing the index write.
 */
async function readArchiveHeader(file: string): Promise<ArchiveHeaderHint | undefined> {
	const raw = await readOptional(file);
	const newline = raw.indexOf("\n");
	const firstLine = (newline === -1 ? raw : raw.slice(0, newline)).trim();
	if (!firstLine.startsWith("{")) return undefined;
	let parsed: unknown;
	try {
		parsed = JSON.parse(firstLine);
	} catch {
		return undefined;
	}
	if (typeof parsed !== "object" || parsed === null) return undefined;
	const header = parsed as { createdAt?: unknown; timestamp?: unknown; origin?: unknown };
	const stamp = typeof header.createdAt === "number" ? header.createdAt : typeof header.timestamp === "string" ? Date.parse(header.timestamp) : Number.NaN;
	if (!Number.isFinite(stamp)) return undefined;
	return { date: new Date(stamp).toISOString().slice(0, 10), ...(header.origin === "subagent" ? { origin: "subagent" as const } : {}) };
}

/** A directory name that could be a session id; `INDEX.md`, `.gitignore` and zips fall out later. */
const SESSION_DIRECTORY = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;

/**
 * Rewrite `INDEX.md` from what is on disk: one row per session directory, nothing else.
 *
 * This is the whole point of the generated index. Appending made two states possible that the design
 * could not fix, only repair: a directory with no row (a wholesale migration, an install whose
 * archive path never ran) and a row with no directory (a purged archive). Generating makes both
 * unwritable — a row exists exactly when the directory does. Duplicates are likewise impossible,
 * because the directory name is the key.
 *
 * Directories without `meta.json` are the migration case: their title comes from the old index (the
 * only record of what a session was called) or, failing that, the archive header, and the metadata
 * is written back so the next generation does not repeat the read.
 */
async function regenerateSessionIndex(projectRoot: string): Promise<void> {
	const indexFile = sessionIndexFile(projectRoot);
	const existing = await readOptional(indexFile);
	// Date and title for a session that predates `meta.json`: the rendered index is the only cheap
	// record, and reading every archive instead would open megabytes on every write.
	const hints = new Map(parseSessionIndex(normalizeLegacyIndex(existing)).map((entry) => [entry.id, entry]));
	const legacyFile = legacySessionIndexFile(projectRoot);
	// Read the pre-move file through the adoption reader, which stats before it reads: a FIFO or a
	// directory at that path must not block the index write (reading a FIFO with no writer never
	// returns, and every later write would queue behind this one).
	const adopted = await readLegacyIndexForAdoption(legacyFile);
	for (const entry of parseSessionIndex(adopted?.body ?? "")) {
		if (!hints.has(entry.id)) hints.set(entry.id, entry);
	}

	const logs = logsDir(projectRoot);
	// No archive directory means nothing has ever been archived here: stop before the write, which
	// would otherwise fail on a missing parent (the write path always has one, because recording a
	// session's metadata creates `session-logs/<id>/` first).
	let names: string[];
	try {
		names = await readdir(logs);
	} catch {
		return;
	}
	const rows: SessionMeta[] = [];
	for (const name of names.sort()) {
		if (!SESSION_DIRECTORY.test(name)) continue;
		const dir = path.join(logs, name);
		if (!(await isDirectory(dir))) continue;
		let meta = await readSessionMeta(dir);
		if (meta === undefined) {
			const id = safeSessionId(name);
			const hint = hints.get(id);
			const header = hint === undefined ? await readArchiveHeader(path.join(dir, "session.jsonl")) : undefined;
			// Neither an index row nor a readable archive header: not a session directory.
			if (hint === undefined && header === undefined) continue;
			meta = {
				id,
				date: hint?.date ?? header!.date,
				title: hint?.title ?? "Untitled session",
				...(header?.origin === "subagent" ? { kind: "subagent" as const } : {}),
			};
			await writeSessionMeta(dir, meta);
		}
		// A delegated child's archive is written for forensics, not for navigation: the archive path
		// refuses to index it, and the generated index has to agree or the two disagree silently.
		if (meta.kind === "subagent") continue;
		rows.push(meta);
	}
	rows.sort((left, right) => (left.date === right.date ? (left.id < right.id ? -1 : left.id > right.id ? 1 : 0) : left.date < right.date ? -1 : 1));
	const document = [HEADING, "", ...rows.map((row) => sessionIndexLineFor(row)), ""].join("\n");
	if (document !== existing) await writeAtomic(indexFile, document);

	// Adopt a pre-move `<memory>/session-index.md`: every line it holds is now either a directory (and
	// therefore a row) or has no archive at all. Its source is released only once each of its ids
	// appears — a line whose directory is gone is the only copy left, so it stays on disk rather than
	// being deleted with the file. Re-stat first, because an older host can still append to that path.
	if (adopted !== undefined && adopted.ids.every((entryId) => document.includes(`[${safeSessionId(entryId)}](`)) && (await untouchedSince(legacyFile, adopted))) {
		await rm(legacyFile, { force: true }).catch(() => undefined);
	}
}

/** One write chain per project so concurrent sessions cannot interleave index writes. */
const queues = new Map<string, Promise<void>>();

/**
 * Run one index mutation under the in-process chain and the cross-process lock.
 *
 * `queues` orders writers inside this process only, and generation is a read-modify-write over the
 * whole directory listing: two hosts doing it at once interleave. The same lock the memory journal
 * uses therefore covers the metadata write and the regeneration together.
 */
function withIndexQueue(projectRoot: string, work: () => Promise<void>): Promise<void> {
	const key = projectRoot;
	const previous = queues.get(key) ?? Promise.resolve();
	const next = previous.catch(() => undefined).then(() => withMemoryLock(sessionIndexLockTarget(projectRoot), work));
	queues.set(key, next);
	void next.catch(() => undefined).finally(() => {
		if (queues.get(key) === next) queues.delete(key);
	});
	return next;
}

/**
 * Fields a per-turn refresh has no opinion about, carried over from the stored metadata.
 *
 * The archive write rebuilds a session's metadata from the live session on every settle, and that
 * rebuild knows nothing about decisions taken elsewhere: which task the session was bound to
 * (`/context task`), which session it continues (`kind` / `parentId`, written by the handoff).
 * Overwriting them would erase a binding on the next turn — the failure would look like the command
 * never worked. A field the new metadata does carry always wins, so the command's own write is not
 * fought by this merge.
 */
function preserveForeign(meta: SessionMeta, existing: SessionMeta | undefined): SessionMeta {
	if (existing === undefined) return meta;
	return {
		...meta,
		...(meta.kind === undefined && existing.kind !== undefined ? { kind: existing.kind } : {}),
		...(meta.parentId === undefined && existing.parentId !== undefined ? { parentId: existing.parentId } : {}),
		...(meta.task === undefined && existing.task !== undefined ? { task: existing.task } : {}),
	};
}

/** Record a session's metadata, then regenerate the index from the directory listing. */
function queueIndexWrite(projectRoot: string, meta: SessionMeta): Promise<void> {
	return withIndexQueue(projectRoot, async () => {
		const dir = path.join(logsDir(projectRoot), meta.id);
		await writeSessionMeta(dir, preserveForeign(meta, await readSessionMeta(dir)));
		await regenerateSessionIndex(projectRoot);
	});
}

/**
 * Bind (or unbind) this session to a task, then refresh the index.
 *
 * The binding lives in `meta.json` so it survives a restart, and it is written through the same
 * queue and locked section as every other metadata write: a concurrent archive write must not
 * interleave with it, or the binding and the row would disagree. `undefined` removes the field —
 * an unbind is an authored decision, not a missing value, so it must not be restored by the merge
 * above.
 * @param projectRoot - the project whose `session-logs/` holds this session's metadata.
 * @param session - the live session being bound.
 * @param task - the slug to bind, or `undefined` to unbind.
 * @returns the metadata that landed.
 */
export function setSessionTask(projectRoot: string, session: Session, task: string | undefined): Promise<SessionMeta> {
	const base = sessionMetaOf(session);
	let written: SessionMeta = base;
	return withIndexQueue(projectRoot, async () => {
		const dir = path.join(logsDir(projectRoot), base.id);
		const existing = await readSessionMeta(dir);
		const { task: _previous, ...rest } = preserveForeign(base, existing);
		written = task === undefined ? rest : { ...rest, task };
		await writeSessionMeta(dir, written);
		await regenerateSessionIndex(projectRoot);
	}).then(() => written);
}

/** Project roots whose startup reconcile already ran in this process. */
const reconciled = new Set<string>();

/**
 * Regenerate the index once per project per process, at startup.
 *
 * Every index write already reconciles, so this is not a repair path: it is what makes a directory
 * that appeared without any session write (a wholesale migration, an install whose archive path
 * never ran) show up without waiting for the next unrelated write. Idempotent by construction —
 * generation reads the directory listing, not the document — so a repeat costs one scan and no
 * change. A failed pass drops the marker so a later trigger can retry; a silent failure would leave
 * the index wrong until some session happened to write.
 */
export function reconcileSessionIndexOnce(projectRoot: string): Promise<void> {
	if (reconciled.has(projectRoot)) return Promise.resolve();
	reconciled.add(projectRoot);
	return withIndexQueue(projectRoot, () => regenerateSessionIndex(projectRoot)).catch((error: unknown) => {
		reconciled.delete(projectRoot);
		throw error;
	});
}

/** Record this session in the index. Idempotent: the directory is the key and the title is refreshed. */
export function queueSessionIndexEntry(projectRoot: string, session: Session): Promise<void> {
	return queueIndexWrite(projectRoot, sessionMetaOf(session));
}

/**
 * Record one index line (import and backfill callers that have a rendered line rather than a session).
 *
 * The line is parsed back into metadata rather than kept as text: the index is a projection, so a
 * line that never reached `meta.json` would vanish on the next generation. A line the pattern cannot
 * parse keeps its own text as the title and today's date.
 */
export function queueIndexLine(projectRoot: string, id: string, line: string): Promise<void> {
	const match = LINE_PATTERN.exec(line.trim());
	return queueIndexWrite(projectRoot, {
		id: safeSessionId(id),
		date: match?.[3] ?? new Date().toISOString().slice(0, 10),
		title: match?.[4]?.trim() ?? line.trim(),
	});
}
